import { useEffect, useMemo, useRef, useState } from "react";
import type { DemoVoiceRole } from "@workspace/api-client-react";
import { Check, Loader2, Play, RefreshCw, Search, Square, Volume2, AlertTriangle } from "lucide-react";
import { useNarration, VOICE_ROLES } from "./narration-provider";
import { voiceError } from "@/lib/narrated-playback";
import { IDLE_VOICE_PREVIEW, VoicePreviewController, type VoicePreviewState } from "@/lib/voice-preview";
import { SectionLink } from "@/components/section-link";
import { filterVoiceCatalog, voiceFilterOptions, voiceLabelKey, voiceLabelText, voiceLanguageAccents } from "@/lib/voice-catalog";

const roleLabel = (id: DemoVoiceRole | null) => VOICE_ROLES.find(r => r.id === id)?.label ?? "";
const initials = (name: string) => name.split(/\s+/).filter(Boolean).slice(0, 2).map(w => w[0]!.toUpperCase()).join("") || "V";

export function VoiceTalentControls() {
  const n = useNarration();
  const [preview, setPreview] = useState<VoicePreviewState>(IDLE_VOICE_PREVIEW);
  const [target, setTarget] = useState<DemoVoiceRole>("caller");
  const [query, setQuery] = useState("");
  const [language, setLanguage] = useState("");
  const [accent, setAccent] = useState("");
  const [announce, setAnnounce] = useState("");

  const loadRef = useRef(n.getPreviewClip);
  loadRef.current = n.getPreviewClip;
  const controllerRef = useRef<VoicePreviewController | null>(null);
  const { registerPreview } = n;
  useEffect(() => {
    const c = new VoicePreviewController({
      load: (role, id, signal) => loadRef.current(role, id, signal),
      onChange: setPreview,
    });
    controllerRef.current = c;
    const unregister = registerPreview(c.stop);
    return () => { unregister(); c.dispose(); if (controllerRef.current === c) controllerRef.current = null; };
  }, [registerPreview]);
  useEffect(() => { controllerRef.current?.setVolume(n.volume); }, [n.volume]);

  const voiceName = (id: string) => n.voices.find(v => v.id === id)?.name ?? (id ? `Unavailable voice (${id})` : "Not assigned");
  const languages = useMemo(() => voiceFilterOptions(n.voices, "language"), [n.voices]);
  const accents = useMemo(() => voiceFilterOptions(n.voices, "accent"), [n.voices]);
  const filtered = useMemo(() => filterVoiceCatalog(n.voices, query, language, accent), [n.voices, query, language, accent]);
  const clearFilters = () => { setQuery(""); setLanguage(""); setAccent(""); };

  const togglePreview = (voiceId: string, name: string) => {
    const c = controllerRef.current;
    if (!c) return;
    const busy = preview.voiceId === voiceId && preview.role === target && (preview.status === "loading" || preview.status === "playing");
    if (busy) { c.stop(); setAnnounce(`Stopped preview of ${name}.`); return; }
    n.stopPlayback();
    setAnnounce(`Preparing ${name} as ${roleLabel(target)}.`);
    void c.play(target, voiceId);
  };
  const apply = (voiceId: string, name: string) => {
    n.setVoice(target, voiceId);
    setAnnounce(`${name} applied to ${roleLabel(target)}. Demos paused.`);
  };

  const statusText = preview.status === "loading" ? `Preparing ${voiceName(preview.voiceId ?? "")} as ${roleLabel(preview.role)}…`
    : preview.status === "playing" ? `Playing ${voiceName(preview.voiceId ?? "")} as ${roleLabel(preview.role)}`
    : "";

  return (
    <section id="voice-talent" data-section-nav aria-label="ElevenLabs voice talent" data-testid="narration-settings"
      className="vt-root mt-6 scroll-mt-24 overflow-hidden rounded-2xl border border-[#203524]/20 bg-[#F7F9F1] text-[#11110D]">
      <style>{`
        .vt-in{animation:vt-in .28s cubic-bezier(.2,.7,.2,1) both}
        @keyframes vt-in{from{opacity:0;transform:translateY(4px)}to{opacity:1;transform:none}}
        .vt-bar{transform-origin:bottom;animation:vt-eq .9s ease-in-out infinite}
        @keyframes vt-eq{0%,100%{transform:scaleY(.35)}50%{transform:scaleY(1)}}
        @media (prefers-reduced-motion:reduce){.vt-in,.vt-bar{animation:none!important}.vt-root *{transition:none!important}}
      `}</style>

      {/* Header band */}
      <div className="on-dark flex flex-wrap items-center justify-between gap-3 bg-[#203524] px-5 py-4 text-[#F5F5F2]">
        <div className="min-w-0">
          <p className="eyebrow text-[#D1F470]">Voice talent</p>
          <h3 className="mt-1 flex items-center gap-2 font-semibold"><Volume2 className="h-4 w-4" aria-hidden />ElevenLabs voice overlay<SectionLink id="voice-talent" label="Voice Talent" dark /></h3>
          <p className="mt-1 max-w-2xl text-xs leading-relaxed opacity-75">
            Previews are prepared sample dialogue generated by ElevenLabs and may use account credits. Not a real call, and no custom customer text. Applying a voice pauses the demo.
          </p>
        </div>
        {n.auth.isAuthenticated ? (
          <label className="inline-flex min-h-11 items-center gap-2 rounded-full bg-white/10 px-4 text-sm font-semibold">
            <input type="checkbox" checked={n.wanted} disabled={n.preferencesReady === false} onChange={e => n.setEnabled(e.target.checked)} className="h-4 w-4 accent-[#D1F470]" data-testid="toggle-narration" />
            Voice overlay {n.enabled ? "on" : "off"}
          </label>
        ) : (
          <button type="button" onClick={() => n.auth.login()} className="min-h-11 rounded-full bg-[#D1F470] px-4 text-sm font-semibold text-[#203524] transition-transform hover:-translate-y-px" data-testid="button-narration-sign-in">
            Sign in for voice overlay
          </button>
        )}
      </div>

      <p className="sr-only" role="status" aria-live="polite" data-testid="status-voice-announce">{announce}</p>

      <div className="p-5">
        {n.auth.isAuthenticated && (
          <div className="mb-4 flex flex-wrap items-center gap-3 text-xs">
            <p role={n.preferencesError ? "alert" : "status"} data-testid="status-narration-preferences">{n.preferencesStatus}</p>
            {n.preferencesError && <button type="button" onClick={n.retryPreferences} className="min-h-11 font-semibold underline">Retry settings</button>}
            <button type="button" disabled={n.preferencesReady === false} onClick={n.resetPreferences} className="min-h-11 font-semibold underline" data-testid="button-reset-narration">
              Reset my narration settings
            </button>
            <p className="w-full opacity-70">Voice assignments, overlay mode, volume and captions save automatically to your account. Restoring or resetting settings never starts playback.</p>
          </div>
        )}
        {(n.unavailableRoles?.length ?? 0) > 0 && (
          <p role="alert" className="mb-4 rounded-xl border border-[#9A4C2C]/30 p-3 text-sm" data-testid="error-saved-voices">
            Saved voices for {n.unavailableRoles.map(role => role.label).join(", ")} are no longer in the available voice catalog.
            Narration will not use substitute voices. Enable the overlay to apply replacements below, or reset your settings to the current catalog defaults.
          </p>
        )}
        {!n.auth.isAuthenticated && <p className="text-xs opacity-70">Visual-only playback is available without signing in. Speech generation requires a signed-in session.</p>}
        {n.auth.isAuthenticated && !n.enabled && (
          <p className="text-xs opacity-70" data-testid="text-visual-only">Visual-only mode. Enable the overlay to browse, preview and apply the connected ElevenLabs voices.</p>
        )}

        {n.enabled && (
          <>
            {n.catalog.isFetching && (
              <div role="status" className="space-y-2" data-testid="status-voice-catalog-loading">
                <p className="flex items-center gap-2 text-sm"><Loader2 className="h-4 w-4 animate-spin" aria-hidden />Loading available ElevenLabs voices…</p>
                {n.voices.length === 0 && [0, 1, 2].map(i => <div key={i} className="h-12 rounded-xl bg-[#203524]/[.06]" aria-hidden />)}
              </div>
            )}
            {n.catalog.error && (
              <div role="alert" className="mt-3 rounded-xl border border-[#9A4C2C]/30 bg-white p-3 text-sm" data-testid="error-voice-catalog">
                <p className="flex items-start gap-2"><AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-[#9A4C2C]" aria-hidden />{voiceError(n.catalog.error)}</p>
                <button type="button" onClick={() => void n.catalog.refetch()} disabled={n.catalog.isFetching} className="mt-2 inline-flex min-h-11 items-center gap-2 font-semibold underline underline-offset-4 disabled:opacity-50"><RefreshCw className="h-4 w-4" aria-hidden />Retry voice connection</button>
              </div>
            )}
            {!n.catalog.isFetching && !n.catalog.error && n.voices.length === 0 && (
              <div className="rounded-xl border border-dashed border-[#203524]/30 p-4 text-sm" data-testid="empty-voice-catalog">
                <p className="font-semibold">No voices available in the connected ElevenLabs account.</p>
                <p className="mt-1 text-xs opacity-70">Add voices in ElevenLabs, then reload the list.</p>
                <button type="button" onClick={() => void n.catalog.refetch()} className="mt-2 inline-flex min-h-11 items-center gap-2 text-sm font-semibold underline underline-offset-4"><RefreshCw className="h-4 w-4" aria-hidden />Reload voices</button>
              </div>
            )}

            {n.voices.length > 0 && (
              <div className="grid gap-5 lg:grid-cols-[minmax(0,17rem)_minmax(0,1fr)]">
                {/* Current cast + role chooser */}
                <div>
                  <h4 className="eyebrow opacity-70" id="vt-cast">Current cast / Apply to</h4>
                  <div role="group" aria-labelledby="vt-cast" className="mt-2 grid grid-cols-2 gap-2 lg:grid-cols-1">
                    {VOICE_ROLES.map(role => {
                      const active = role.id === target;
                      return (
                        <button key={role.id} type="button" aria-pressed={active} onClick={() => { controllerRef.current?.stop(); setTarget(role.id); }}
                          data-testid={`button-role-${role.id}`}
                          className={`min-h-14 min-w-0 rounded-xl border px-3 py-2 text-left transition-colors ${active ? "border-[#203524] bg-[#203524] text-[#F5F5F2]" : "border-[#203524]/15 bg-white hover:border-[#203524]/40"}`}>
                          <span className={`block text-[11px] font-semibold uppercase tracking-wider ${active ? "text-[#D1F470]" : "opacity-60"}`}>{role.label}</span>
                          <span className="block truncate text-sm font-semibold" data-testid={`text-cast-${role.id}`}>{voiceName(n.selected[role.id])}</span>
                        </button>
                      );
                    })}
                  </div>
                  {n.voices.length < 3 && <p className="mt-2 text-xs opacity-70">Only {n.voices.length} {n.voices.length === 1 ? "voice is" : "voices are"} available. Add voices in ElevenLabs to give Caller, AI Agent and Human Agent distinct voices.</p>}
                </div>

                {/* Catalogue */}
                <div className="min-w-0">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <h4 className="eyebrow opacity-70">Catalogue · {filtered.length} of {n.voices.length}</h4>
                    <p className="text-xs">Auditioning as <strong data-testid="text-target-role">{roleLabel(target)}</strong></p>
                  </div>
                  <label className="relative mt-2 block">
                    <span className="sr-only">Search voices</span>
                    <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 opacity-50" aria-hidden />
                    <input type="search" value={query} onChange={e => setQuery(e.target.value)} placeholder="Search voices by name"
                      data-testid="input-voice-search" className="min-h-11 w-full rounded-xl border border-[#203524]/25 bg-white pl-9 pr-3 text-sm" />
                  </label>
                  <div className="mt-2 grid gap-2 sm:grid-cols-2">
                    <label className="min-w-0 text-xs font-semibold">Language
                      <select value={language} onChange={e => setLanguage(e.target.value)} data-testid="select-voice-language"
                        className="mt-1 min-h-11 w-full rounded-xl border border-[#203524]/25 bg-white px-3 text-sm">
                        <option value="">All languages</option>
                        {languages.map(option => <option key={option.value} value={option.value}>{option.label}</option>)}
                      </select>
                    </label>
                    <label className="min-w-0 text-xs font-semibold">Accent
                      <select value={accent} onChange={e => setAccent(e.target.value)} data-testid="select-voice-accent"
                        className="mt-1 min-h-11 w-full rounded-xl border border-[#203524]/25 bg-white px-3 text-sm">
                        <option value="">All accents</option>
                        {accents.map(option => <option key={option.value} value={option.value}>{option.label}</option>)}
                      </select>
                    </label>
                  </div>
                  <p className="mt-2 text-xs leading-relaxed opacity-70">Language/accent pairs come from ElevenLabs catalog labels and verified entries for this demo’s speech model. “Not provided” means no label was supplied, not that a language is unsupported. Filters do not translate the prepared sample dialogue.</p>
                  {(query || language || accent) && <button type="button" onClick={clearFilters} data-testid="button-clear-voice-filters" className="min-h-11 text-xs font-semibold underline underline-offset-4">Clear filters</button>}
                  <p className="sr-only" role="status" aria-live="polite">{filtered.length} of {n.voices.length} voices match the current filters.</p>
                  {n.lines?.find(line => line.role === target) && <p className="mt-2 text-xs leading-relaxed opacity-70" data-testid="text-preview-script">Sample: {n.lines.find(line => line.role === target)?.text}</p>}
                  {statusText && (
                    <div className="vt-in mt-2 flex items-center justify-between gap-2 rounded-lg bg-[#D1F470]/50 px-3 py-2 text-xs font-semibold">
                      <p role="status" className="flex items-center gap-2" data-testid="status-voice-preview">
                        {preview.status === "loading" ? <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden /> : <Eq />}{statusText}
                      </p>
                      <button type="button" className="inline-flex min-h-11 shrink-0 items-center gap-1 rounded-full border border-[#203524]/30 px-3" onClick={() => controllerRef.current?.stop()} aria-label="Stop voice preview" data-testid="button-stop-preview"><Square className="h-3 w-3" aria-hidden />Stop</button>
                    </div>
                  )}
                  <ul className="mt-2 max-h-[26rem] divide-y divide-[#203524]/10 overflow-y-auto rounded-xl border border-[#203524]/15 bg-white" data-testid="list-voices">
                    {filtered.length === 0 && <li className="p-4 text-sm opacity-70" data-testid="empty-voice-search">No voices match the current search and language/accent filters. Clear filters to see all voices.</li>}
                    {filtered.map(v => {
                      const mine = preview.voiceId === v.id && preview.role === target;
                      const loading = mine && preview.status === "loading";
                      const playing = mine && preview.status === "playing";
                      const err = mine && preview.status === "error" ? preview.error : null;
                      const applied = VOICE_ROLES.filter(r => n.selected[r.id] === v.id);
                      const isTarget = n.selected[target] === v.id;
                      return (
                        <li key={v.id} className={`px-3 py-2.5 transition-colors ${playing || loading ? "bg-[#EEF4E2]" : ""}`} data-testid={`row-voice-${v.id}`}>
                          <div className="flex flex-wrap items-center gap-3">
                            <span aria-hidden className="grid h-9 w-9 shrink-0 place-items-center rounded-full bg-[#203524] text-xs font-semibold text-[#D1F470]">{playing ? <Eq light /> : initials(v.name)}</span>
                            <div className="min-w-0 flex-1">
                              <p className="truncate text-sm font-semibold">{v.name}</p>
                              <ul className="mt-1 flex flex-wrap gap-1 text-[11px] opacity-80" aria-label={`Language and accent for ${v.name}`}>
                                {voiceLanguageAccents(v).map((pair, index) => (
                                  <li key={index} className="rounded-md bg-[#203524]/5 px-2 py-1">
                                    Language: {voiceLabelText(voiceLabelKey(pair.language), "language")} · Accent: {voiceLabelText(voiceLabelKey(pair.accent), "accent")}
                                  </li>
                                ))}
                              </ul>
                              {applied.length > 0 && (
                                <div className="mt-0.5 flex flex-wrap gap-1">
                                  {applied.map(r => <span key={r.id} className="vt-in inline-flex items-center gap-1 rounded-full bg-[#D1F470] px-2 py-0.5 text-[10px] font-semibold text-[#203524]" data-testid={`badge-applied-${v.id}-${r.id}`}><Check className="h-3 w-3" aria-hidden />{r.label}</span>)}
                                </div>
                              )}
                            </div>
                            <div className="flex w-full gap-2 sm:w-auto">
                              <button type="button" onClick={() => togglePreview(v.id, v.name)}
                                aria-label={loading || playing ? `Stop preview of ${v.name}` : `Preview ${v.name} as ${roleLabel(target)}`}
                                data-testid={`button-preview-${v.id}`}
                                className="inline-flex min-h-11 flex-1 items-center justify-center gap-1.5 rounded-full border border-[#203524]/30 px-3 text-xs font-semibold hover:border-[#203524] sm:flex-none">
                                {loading ? <><Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden />Stop</> : playing ? <><Square className="h-3.5 w-3.5" aria-hidden />Stop</> : <><Play className="h-3.5 w-3.5" aria-hidden />{err ? "Retry preview" : "Preview"}</>}
                              </button>
                              <button type="button" onClick={() => apply(v.id, v.name)} disabled={isTarget}
                                aria-label={isTarget ? `${v.name} is applied to ${roleLabel(target)}` : `Apply ${v.name} to ${roleLabel(target)}`}
                                data-testid={`button-apply-${v.id}`}
                                className="inline-flex min-h-11 flex-1 items-center justify-center gap-1.5 rounded-full bg-[#203524] px-3 text-xs font-semibold text-[#D1F470] disabled:bg-[#203524]/10 disabled:text-[#203524] sm:flex-none">
                                {isTarget ? <><Check className="h-3.5 w-3.5" aria-hidden />Applied</> : `Apply to ${roleLabel(target)}`}
                              </button>
                            </div>
                          </div>
                          {err && <p role="alert" className="vt-in mt-2 rounded-lg bg-[#9A4C2C]/10 px-3 py-2 text-xs text-[#6E3317]" data-testid={`error-preview-${v.id}`}>{err}</p>}
                        </li>
                      );
                    })}
                  </ul>
                </div>
              </div>
            )}

            <div className="mt-5 flex flex-wrap items-center gap-x-6 gap-y-2 border-t border-[#203524]/10 pt-3">
              <label className="flex min-h-11 items-center gap-3 text-xs font-semibold">Volume
                <input aria-label="Narration volume" type="range" min="0" max="1" step="0.05" value={n.volume} onChange={e => n.setVolume(Number(e.target.value))} className="w-28 accent-[#203524]" data-testid="input-narration-volume" />
                <span className="mono w-9">{Math.round(n.volume * 100)}%</span>
              </label>
              <label className="flex min-h-11 items-center gap-2 text-xs font-semibold"><input type="checkbox" checked={n.captions} onChange={e => n.setCaptions(e.target.checked)} className="h-4 w-4 accent-[#203524]" data-testid="toggle-captions" />Dialogue captions</label>
              <button type="button" onClick={() => n.setEnabled(false)} className="min-h-11 text-xs font-semibold underline underline-offset-4" data-testid="button-visual-only">Use visual-only playback</button>
            </div>
          </>
        )}
      </div>
    </section>
  );
}

function Eq({ light }: { light?: boolean }) {
  return (
    <span aria-hidden className="inline-flex h-3.5 items-end gap-[2px]">
      {[0, 0.15, 0.3].map(d => <span key={d} className={`vt-bar block h-full w-[3px] rounded-sm ${light ? "bg-[#D1F470]" : "bg-[#203524]"}`} style={{ animationDelay: `${d}s` }} />)}
    </span>
  );
}
