import { build } from "esbuild";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
const dir=await mkdtemp(join(tmpdir(),"routing-check-"));
try {
  await build({stdin:{resolveDir:resolve("artifacts/zcc-depot"),loader:"ts",contents:`
import assert from "node:assert/strict";
import {simulateRouting as run,DEFAULT_CONFIG as D,advancePlayback as step} from "./src/lib/routing-engine";
let checks=0;
const ok=(v,m)=>{assert.ok(v,m);checks++};
const config=(over={})=>({...D,...over});
const ids=["queue","skills","priority","longest","vip","preferred","intent","hours","overflow","language","capacity","external"];
for(const id of ids){
 const r=run(id,config());
 ok(r.agents.length>=3,id+" has three agents");
 ok(r.events[0].state==="Idle"&&r.events.at(-1).state==="Completed",id+" complete lifecycle");
 ok(r.events.every((e,i)=>!i||e.at>=r.events[i-1].at),id+" monotonic timing");
 ok(JSON.stringify(r)===JSON.stringify(run(id,config())),id+" deterministic");
 ok(!r.selectedAgent||r.agents.find(a=>a.id===r.selectedAgent)?.eligible,id+" selected agent eligible");
 const blocked=run(id,config({availability:"none"}));
 ok(!blocked.selectedAgent,id+" never selects unavailable agent");
}
ok(run("queue",config({intent:"Sales"})).destination==="Sales","IVR Sales");
ok(run("queue",config({intent:"Billing"})).destination==="Billing","IVR Billing");
ok(run("longest",config()).selectedAgent==="c","longest Available eligible agent");
ok(run("longest",config({availability:"c"})).selectedAgent==="a","unavailable longest agent excluded");
ok(run("priority",config({priority:1,delay:0})).destination==="Sales","lower numeric priority first");
ok(run("priority",config({priority:3})).destination==="Support","priority affects queue decision");
ok(run("priority",config({delay:30})).destination==="Support","delay excludes too-young contact even with idle agents");
ok(run("priority",config({priority:2})).destination==="Support","same priority oldest contact first");
ok(run("vip",config({tier:"VIP"})).destination==="VIP","VIP attributes");
ok(run("vip",config()).destination==="Support","standard attributes");
ok(run("preferred",config({preferred:"a"})).selectedAgent==="a","preferred Available agent");
const preferred=run("preferred",config({preferred:"a",availability:"a",timeout:45}));
ok(preferred.selectedAgent==="c"&&preferred.wait===45,"preferred expiry and fallback");
ok(preferred.events.some(e=>e.state==="Fallback"&&e.detail.includes("expired")),"preferred fallback timeline");
const skills=run("skills",config({language:"French",proficiency:5,certification:"Payments"}));
ok(skills.selectedAgent==="a"&&skills.wait===30,"proficiency relaxes but certifications remain");
ok(run("skills",config({certification:"Technical",product:"Enterprise"})).selectedAgent==="c","product and certification constraints");
ok(run("language",config({language:"Spanish",proficiency:5})).selectedAgent==="b","Spanish proficient agent");
ok(run("language",config({language:"French",proficiency:5})).selectedAgent==="c","French proficient agent");
ok(run("intent",config({intent:"Billing"})).events.some(e=>e.label==="Amazon Lex: Billing intent"),"intent classifier explicit");
ok(run("hours",config({schedule:"After hours"})).destination==="Alternate regional team","after hours");
ok(run("hours",config({schedule:"Weekend"})).destination==="Voicemail","weekends");
ok(run("hours",config({schedule:"Holiday"})).destination==="Voicemail","holidays");
ok(run("overflow",config({depth:4,threshold:5})).destination==="Support","below overflow threshold");
ok(run("overflow",config({depth:5,threshold:5})).destination==="Backup","at overflow threshold");
ok(run("capacity",config()).selectedAgent==="b","fewest active contacts, not longest idle, across channels");
const cap=run("capacity",config({channel:"Chat",capacity:1}));
ok(!cap.agents.find(a=>a.id==="a").eligible,"channel capacity enforced");
const cross=run("capacity",config({crossChannel:false}));
ok(!cross.agents.find(a=>a.id==="a").eligible&&!cross.agents.find(a=>a.id==="c").eligible,"cross-channel restrictions");
ok(run("external",config({tier:"VIP"})).destination==="VIP","lookup attributes");
ok(run("external",config({tier:"VIP",lookup:"Error"})).destination==="Support","failed lookup safe branch");
const lookup=run("external",config({lookup:"Timeout",timeout:8}));
ok(lookup.events.some(e=>e.state==="Fallback"&&e.node==="integration")&&lookup.wait===0,"lookup latency is not queue wait");
const none=run("queue",config({availability:"none"}));
ok(!none.selectedAgent&&none.destination==="Voicemail","no agent configured fallback");
let p={index:0,running:false};
p=step(p,"start",4);ok(p.running&&p.index===0,"start");
p=step(p,"tick",4);ok(p.index===1,"tick");
p=step(p,"pause",4);ok(!p.running,"pause");
ok(step(p,"tick",4).index===1,"paused tick stays put");
p=step(p,"resume",4);ok(p.running,"resume");
p=step(p,"next",4);ok(p.index===2&&!p.running,"next pauses");
p=step(p,"previous",4);ok(p.index===1&&!p.running,"previous pauses");
p=step(p,"reset",4);ok(p.index===0&&!p.running,"reset");
p=step(p,"replay",4);ok(p.index===0&&p.running,"replay");
for(let i=0;i<6;i++)p=step(p,"tick",4);
ok(p.index===3&&!p.running,"completion stops");
ok(!step(p,"resume",4).running,"cannot resume completed");
ok(step({index:0,running:false},"previous",4).index===0,"previous bounded");
console.log(checks+" routing engine checks passed");
`},bundle:true,platform:"node",outfile:join(dir,"checks.cjs")});
  const result=spawnSync(process.execPath,[join(dir,"checks.cjs")],{stdio:"inherit"});
  if(result.status)process.exitCode=result.status;
} finally { await rm(dir,{recursive:true,force:true}); }
